// Открытие учебного раздела

function openTopic(topicId) {
    const topic = topicsData[topicId];

    if (!topic) return;

    const main = document.querySelector("main");

    main.innerHTML = `
        <section class="quiz topic-content">

            <button onclick="location.reload()">
                ← На главную
            </button>

            <h1>${topic.title}</h1>
            <p>${topic.subtitle}</p>

            <h2>Теория</h2>

            ${topic.theory.map((item, index) => `
                <div class="topic">
                    <h3>${index + 1}. ${item.title}</h3>
                    <p>${item.text}</p>
                </div>
            `).join("")}

            <h2>Важные даты</h2>

            <div class="topic">
                ${topic.dates.map(date => `
                    <p>• ${date}</p>
                `).join("")}
            </div>

            <h2>Основные термины</h2>

            <div class="topic">
                ${topic.terms.map(term => `
                    <p>• ${term}</p>
                `).join("")}
            </div>

            <button onclick="startTopicTest('${topicId}')">
                Пройти тест по теме
            </button>

        </section>
    `;

    window.scrollTo(0, 0);
}


