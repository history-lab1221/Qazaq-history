let currentQuestion = 0;
let score = 0;
let testQuestions = [];

function startTest() {
    currentQuestion = 0;
    score = 0;

    // Выбираем 5 случайных вопросов
    testQuestions = shuffle(questions).slice(0, 20);

    showQuestion();
}

function showQuestion() {
    const main = document.querySelector("main");
    const question = testQuestions[currentQuestion];

    main.innerHTML = `
        <section class="quiz">
            <h2>Тест по истории Казахстана</h2>

            <p class="progress">
                Вопрос ${currentQuestion + 1} из ${testQuestions.length}
            </p>

            <h3>${question.question}</h3>

            <div class="answers">
                ${question.answers.map((answer, index) => `
                    <button class="answer" onclick="checkAnswer(${index})">
                        ${answer}
                    </button>
                `).join("")}
            </div>

            <p id="feedback"></p>

            <button id="nextButton" onclick="nextQuestion()" hidden>
                ${currentQuestion === testQuestions.length - 1
                    ? "Результат"
                    : "Следующий вопрос"}
            </button>
        </section>
    `;
}

function checkAnswer(selected) {
    const question = testQuestions[currentQuestion];

    const buttons = document.querySelectorAll(".answer");
    const feedback = document.getElementById("feedback");

    // Запрещаем повторно нажимать ответы
    buttons.forEach(button => {
        button.disabled = true;
    });

    if (selected === question.correct) {
        score++;

        feedback.innerHTML = `
            <span class="correct">Правильно!</span>
            <p>${question.explanation}</p>
        `;
    } else {
        feedback.innerHTML = `
            <span class="incorrect">Неправильно!</span>
            <p>Правильный ответ: ${question.answers[question.correct]}</p>
            <p>${question.explanation}</p>
        `;
    }

    document.getElementById("nextButton").hidden = false;
}

function nextQuestion() {
    currentQuestion++;

    if (currentQuestion < testQuestions.length) {
        showQuestion();
    } else {
        showResult();
    }
}

function showResult() {
    const main = document.querySelector("main");

    main.innerHTML = `
        <section class="quiz result">
            <h2>Тест завершён!</h2>

            <p>Твой результат:</p>

            <h1>${score} из ${testQuestions.length}</h1>

            <p>
                ${
                    score === testQuestions.length
                    ? "Отличный результат! Все ответы правильные."
                    : score >= 3
                    ? "Хороший результат! Продолжай учиться."
                    : "Повтори тему и попробуй ещё раз."
                }
            </p>

            <button onclick="startTest()">Пройти заново</button>

            <button onclick="location.reload()">
                На главную
            </button>
        </section>
    `;
}

// Перемешивание вопросов
function shuffle(array) {
    const shuffled = [...array];

    for (let i = shuffled.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));

        [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
    }

    return shuffled;
}
