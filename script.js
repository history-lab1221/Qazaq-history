let currentQuestion = 0;
let score = 0;
let testQuestions = [];
let wrongQuestions = [];

function startTest(customQuestions = null) {
    currentQuestion = 0;
    score = 0;
    wrongQuestions = [];

    testQuestions = customQuestions ? customQuestions : shuffle(questions).slice(0, 20);
    showQuestion();
}

function showQuestion() {
    const main = document.querySelector("main");
    const question = testQuestions[currentQuestion];
    const progressPercent = (currentQuestion / testQuestions.length) * 100;

    main.innerHTML = `
        <section class="quiz">
            <h2>Тест по истории Казахстана</h2>
            <div class="progress-container">
                <div class="progress-fill" style="width: ${progressPercent}%"></div>
            </div>
            <p class="progress">Вопрос ${currentQuestion + 1} из ${testQuestions.length}</p>

            <h3>${question.question}</h3>

            <div class="answers">
                ${question.answers.map((answer, index) => `
                    <button class="answer" onclick="checkAnswer(${index}, this)">
                        ${answer}
                    </button>
                `).join("")}
            </div>

            <p id="feedback"></p>

            <button id="nextButton" onclick="nextQuestion()" hidden>
                ${currentQuestion === testQuestions.length - 1 ? "Завершить тест" : "Следующий вопрос →"}
            </button>
        </section>
    `;
}

function checkAnswer(selected, clickedBtn) {
    const question = testQuestions[currentQuestion];
    const buttons = document.querySelectorAll(".answer");
    const feedback = document.getElementById("feedback");

    buttons.forEach((button, idx) => {
        button.disabled = true;
        if (idx === question.correct) {
            button.classList.add("btn-correct");
        }
    });

    if (selected === question.correct) {
        score++;
        feedback.innerHTML = `
            <span class="correct">✅ Правильно!</span>
            <p>${question.explanation}</p>
        `;
    } else {
        clickedBtn.classList.add("btn-wrong");
        wrongQuestions.push(question);
        feedback.innerHTML = `
            <span class="incorrect">❌ Неправильно!</span>
            <p>Правильный ответ: <strong>${question.answers[question.correct]}</strong></p>
            <p>${question.explanation}</p>
        `;
    }

    document.getElementById("nextButton").hidden = false;
}

function nextQuestion() {
    currentQuestion++;

    if (currentQuestion < testQuestions.length) {
        showQuestion();
    } else {
        showResult();
    }
}

function showResult() {
    const main = document.querySelector("main");
    const percent = Math.round((score / testQuestions.length) * 100);

    main.innerHTML = `
        <section class="quiz result">
            <h2>Тест завершён!</h2>
            <p>Твой результат (${percent}%):</p>
            <h1>${score} из ${testQuestions.length}</h1>

            <p>
                ${
                    percent === 100
                    ? "🔥 Идеально! На ЕНТ с такими знаниями будет максимум!"
                    : percent >= 70
                    ? "👍 Хороший результат! Ещё немного практики — и будет идеал."
                    : "📚 Стоит повторить теорию и пройти работу над ошибками."
                }
            </p>

            <div class="main-buttons">
                ${wrongQuestions.length > 0 
                    ? `<button class="retry-btn" onclick="retryMistakes()">🔄 Работа над ошибками (${wrongQuestions.length})</button>` 
                    : ""}
                <button onclick="startTest()">Пройти заново</button>
                <button onclick="location.reload()">На главную</button>
            </div>
        </section>
    `;
}

function retryMistakes() {
    startTest([...wrongQuestions]);
}

// Флеш-карточки
let currentCardIndex = 0;
let isCardFlipped = false;

function openFlashcards() {
    currentCardIndex = 0;
    isCardFlipped = false;
    renderFlashcard();
}

function renderFlashcard() {
    const main = document.querySelector("main");
    const card = flashcardsData[currentCardIndex];

    main.innerHTML = `
        <section class="quiz">
            <button onclick="location.reload()">← На главную</button>
            <h2>🃏 Флеш-карточки (${currentCardIndex + 1} из ${flashcardsData.length})</h2>
            <p>Нажми на карточку, чтобы перевернуть её и проверить себя.</p>

            <div class="flashcard" onclick="flipCard()">
                <h2>${isCardFlipped ? card.back : card.front}</h2>
                <span class="flashcard-hint">
                    ${isCardFlipped ? "(Ответ — нажми, чтобы вернуть вопрос)" : "(Нажми, чтобы увидеть ответ)"}
                </span>
            </div>

            <div class="main-buttons">
                <button onclick="prevCard()">← Назад</button>
                <button onclick="nextCard()">Дальше →</button>
            </div>
        </section>
    `;
}

function flipCard() {
    isCardFlipped = !isCardFlipped;
    renderFlashcard();
}

function nextCard() {
    currentCardIndex = (currentCardIndex + 1) % flashcardsData.length;
    isCardFlipped = false;
    renderFlashcard();
}

function prevCard() {
    currentCardIndex = (currentCardIndex - 1 + flashcardsData.length) % flashcardsData.length;
    isCardFlipped = false;
    renderFlashcard();
}

function shuffle(array) {
    const shuffled = [...array];
    for (let i = shuffled.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
    }
    return shuffled;
}

