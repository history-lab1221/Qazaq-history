// --- Перевод страницы на лету (текст и подсказки в полях) ---
const done = new Map();
function xl(node) {
    if (LANG !== 'kk') return;
    const v = node.nodeValue, t = v.trim();
    if (!t) return;
    const k = tr(t);
    if (k !== t) { done.set(node, v); node.nodeValue = v.replace(t, () => k); }
}
function walk(root) {
    if (root.nodeType === 3) { xl(root); return; }
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let n; while ((n = w.nextNode())) xl(n);
    if (root.querySelectorAll) root.querySelectorAll('[placeholder]').forEach(el => {
        el.dataset.ph = el.dataset.ph || el.placeholder;
        el.placeholder = LANG === 'kk' ? tr(el.dataset.ph) : el.dataset.ph;
    });
}
function setLang(l) {
    LANG = l;
    try { localStorage.setItem('qh_lang', l); } catch (e) {}
    document.documentElement.lang = l === 'kk' ? 'kk' : 'ru';
    done.forEach((o, n) => { if (n.isConnected) n.nodeValue = o; });
    done.clear();
    walk(document.body);
    document.querySelectorAll('.lang button').forEach(b => b.classList.toggle('on', b.dataset.l === l));
}

