// Шаблоны с цифрами и вставками
const R = [
    [/^Вопрос (\d+) из (\d+)\. Выбирай ответ клавишами 1–4\.$/, (m, a, b) => `${a} / ${b}-сұрақ. Жауапты 1–4 пернелерімен таңда.`],
    [/^Твой результат \((\d+)%\):$/, (m, a) => `Нәтижең (${a}%):`],
    [/^(\d{3,4}(?:[–-]\d{3,4})?) (г\.|гг\.)$/, (m, a, b) => a + (b === 'г.' ? ' ж.' : ' жж.')],
    [/^(\d+) из (\d+)$/, '$1 / $2'],
    [/^Флеш-карточки \((\d+) из (\d+)\)$/, 'Флеш-карточкалар ($1 / $2)'],
    [/^🎯 Мои ошибки \((\d+)\)$/, '🎯 Менің қателерім ($1)'],
    [/^🔄 Работа над ошибками \((\d+)\)$/, '🔄 Қателермен жұмыс ($1)'],
    [/^(\d)\. (.+)$/, (m, n, a) => n + '. ' + tr(a)],
    [/^Твой ответ: (.+)$/, (m, a) => 'Сенің жауабың: ' + (a === 'нет ответа' ? 'жауап жоқ' : tr(a))],
    [/^Верно: (.+)$/, (m, a) => 'Дұрыс жауап: ' + tr(a)]
];
function tr(s) {
    if (KK[s]) return KK[s];
    for (const [re, r] of R) if (re.test(s)) return s.replace(re, r);
    return s;
}

